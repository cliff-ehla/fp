	<section class="mt-10 border-t border-gray-200 pt-6">
		<h3 class="text-xl font-medium">Media Archaeology: Retro-Futurism <span class="text-gray-500 font-normal">媒體考古學：昨日之明天</span></h3>
		<ul class="mt-4 space-y-4">
			<li>
				<p>To explore how people in the past imagined the future</p>
				<p class="text-gray-600">探索過去的人們如何構想未來</p>
			</li>
			<li>
				<p>To adopt “retro-futurism” as a creative paradox: applying a vintage aesthetic to futuristic technology</p>
				<p class="text-gray-600">「昨日之明天」作為帶創造性的悖論：將過往或過時的美學應用於未來科技的構想</p>
			</li>
			<li>
				<p>Lectures &amp; workshop series: (1) media archaeology as historiographic and research method; (2) media archaeology as artistic method</p>
				<p class="text-gray-600">系列講座與工作坊：(1) 作為史學與研究方法的媒體考古學；(2) 作為藝術創作方法的媒體考古學。</p>
			</li>
			<li>
				<p>Reactivating old machines</p>
				<p class="text-gray-600">活化、重啟舊機器</p>
			</li>
			<li>
				<p>Excavation: uncovering facts of obsolete media</p>
				<p class="text-gray-600">發掘：揭露過時媒體的真相</p>
			</li>
			<li>
				<p>Exhibition as archiving</p>
				<p class="text-gray-600">「歸檔」作為展覽</p>
			</li>
		</ul>
	</section>

