	<section class="mt-12">
		<h2 class="text-2xl font-medium mb-1">Six keywords <span class="text-gray-500 font-normal">六個關鍵詞</span></h2>
	</section>

	<section class="mt-8 border-t border-gray-200 pt-6">
		<h3 class="text-xl font-medium">Commoning <span class="text-gray-500 font-normal">共有實踐，社群共造</span></h3>
		<ul class="mt-4 space-y-4">
			<li>
				<p>a social-economic process</p>
				<p class="text-gray-600">一個社會經濟過程</p>
			</li>
			<li>
				<p>the social process of people working together to cooperatively create, manage, and protect shared resources</p>
				<p class="text-gray-600">一個共同協作以創造、管理和保護共享資源的社會過程</p>
			</li>
			<li>
				<p>self-governed assets: tools, knowledge, space, skills and expertise</p>
				<p class="text-gray-600">自主管理的資產：工具、知識、空間、技能與專長</p>
			</li>
			<li>
				<p>stewardship over ownership</p>
				<p class="text-gray-600">受託守護重於所有權</p>
			</li>
			<li>
				<p>active practice</p>
				<p class="text-gray-600">積極練習、持續實踐</p>
			</li>
			<li>
				<p>open source: products and resources created and used in a shared way</p>
				<p class="text-gray-600">開源：共享創作背後的知識與資源</p>
			</li>
		</ul>
		<p class="mt-4 text-sm">
			Reference:
			<a class="underline" href="https://culturalfoundation.eu/stories/commoning-the-city-reinventing-togetherness/" target="_blank" rel="noreferrer">Commoning the city: Reinventing togetherness</a>
		</p>
	</section>

	<section class="mt-10 border-t border-gray-200 pt-6">
		<h3 class="text-xl font-medium">Co-individuation <span class="text-gray-500 font-normal">共同個體化，協作生成</span></h3>
		<p class="mt-4">A progressive form of “commoning” — each active FP player is a centre of their own</p>
		<p class="text-gray-600">「共有」的進一步。每個成員都是一個中心</p>
		<ul class="mt-4 space-y-4">
			<li>
				<p>the individual as a dynamic subject</p>
				<p class="text-gray-600">個人 = 動態主體</p>
			</li>
			<li>
				<p>the meaning of the individual grows out of collaboration</p>
				<p class="text-gray-600">個體的意義源自於協作</p>
			</li>
			<li>
				<p>the “I” and the “we” are inseparable realities</p>
				<p class="text-gray-600">「我」與「我們」：不可分割的現實</p>
			</li>
			<li>
				<p>the “I” and the “We” co-individuate through a third element — technical systems or shared tools</p>
				<p class="text-gray-600">「我」與「我們」透過第三種要素 — 技術系統或共享工具 — 實現共同個體化</p>
			</li>
			<li>
				<p>shared background for “being” and “change”: tools, media and creative technics to expand what art entails</p>
				<p class="text-gray-600">「存在」與「變化」的共同背景：工具、媒介與創藝，以擴張「藝術」的所指</p>
			</li>
		</ul>
		<p class="mt-4 text-sm text-gray-600">Ref: Gilbert Simondon, Bernard Stiegler</p>
	</section>

	<section class="mt-10 border-t border-gray-200 pt-6">
		<h3 class="text-xl font-medium">Contributive Economics <span class="text-gray-500 font-normal">貢獻經濟</span></h3>
		<p class="mt-4">Building on “commoning” and “co-individuation”</p>
		<p class="text-gray-600">基於「共有化」與「共個體化」</p>
		<ul class="mt-4 space-y-4">
			<li>
				<p>individuals are active contributors (blurring the line between consumer and producer)</p>
				<p class="text-gray-600">個人是積極的貢獻者（模糊了消費者與生產者之間的界線）</p>
			</li>
			<li>
				<p>income/support systems to achieve “guaranteed minimum” — separated from profit or charity-philanthropic model — to maximize individuals’ time spent in research, art, and community care.</p>
				<p class="text-gray-600">實現「最低收入保障」的收入與支持體系——有別於營利或慈善公益機制——把個人投入於研究、藝術及社區關懷活動的時間最大化。</p>
			</li>
			<li>
				<p>all “Active Players” are rent contributors to make our JCCAC studio service fellow friends and artists. Regular “membership” is replaced by 10 dedicated players plus various flexible “membership” — quarterly or (bi-)annually, based on a proposed project’s duration.</p>
				<p class="text-gray-600">「會員」就是能動者，租金的共同支付者。2026年10月，據點共有10位長年投入的成員。往後彈性的成員制會歡迎「有嘢想（一起）做」的朋友以季度或年度方式加入。</p>
			</li>
		</ul>
	</section>

